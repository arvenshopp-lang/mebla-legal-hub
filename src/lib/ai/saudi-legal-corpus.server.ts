/**
 * توليد نص الموسوعة النظامية الكاملة ليتم دمجه في البرومبت الأساسي للمحامية بيان
 */
export function renderSaudiCorpusPrompt(): string {
  let prompt = `### 🏛️ الموسوعة النظامية والقضائية السعودية الشاملة (Saudi Legal Statutory Encyclopedia & Supreme Court Principles):\n`;

  SAUDI_LEGAL_ENCYCLOPEDIA.forEach((domain, dIdx) => {
    prompt += `\n#### 【${dIdx + 1}】 ${domain.domainName}:\n`;
    domain.statutes.forEach((statute) => {
      prompt += `* **«${statute.name}»** (${statute.royalDecree}):\n`;
      prompt += `  _الوصف:_ ${statute.description}\n`;
      statute.keyArticles.forEach((art) => {
        prompt += `   - **المادة (${art.article})** [${art.topic}]: ${art.summary}\n`;
      });
    });
  });

  prompt += `\n#### 📜 معايير الاستدلال والصياغة القضائية الصارمة للمحامية بيان:
1. **الإسناد النظامي الدقيق:** عند الإجابة أو صياغة المذكرات أو الدفوع أو الاستشارات، اذكري دائماً رقم المادة واسم النظام وتاريخ/رقم المرسوم الملكي بدقة لا تقبل اللبس.
2. **استحضار مدد الطعن النظامية:** (الاستئناف التجاري والمدني 30 يوماً، المستعجل 10 أيام، التظلم الإداري 60 يوماً، دعوى الإلغاء 60 يوماً).
3. **تطبيق نظام الإثبات الحديث:** التمييز بين المحررات الرقمية (م/53) وحدود الشهادة (م/66 - 100 ألف ريال) واليمين الحاسمة.
4. **تطبيق قواعد المعاملات المدنية (1444هـ):** إعمال العقد شريعة المتعاقدين (م/94)، الشرط الجزائي (م/172)، والضمان العشري (م/475).
5. **تطبيق نظام العمل وتعديلاته (1446هـ):** حساب مكافأة نهاية الخدمة (م/84) والتعويض عن الفصل التعسفي (م/77) وحالات فسخ العقد دون مكافأة (م/80).
`;

  return prompt;
}
